import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

/**
 * Rewrites docs/schema.sql from the drizzle migrations.
 *
 * That file exists because the drizzle CLI cannot always reach the
 * deployed database — a Turso token marked Sensitive in Vercel cannot be
 * read back by anything, so `drizzle-kit migrate` has nothing to connect
 * with and the schema has to go in by hand. Which makes it a second copy
 * of the schema, and a second copy drifts: keeping the `__drizzle_migrations`
 * hashes right by hand is exactly the kind of chore that silently stops
 * being done, and a wrong hash there makes the next `db:migrate` replay
 * migration 0000 against tables that already exist.
 *
 * So it is generated. This is the only thing in scripts/ that touches the
 * schema, and it never opens a connection — it reads two files and writes
 * a third.
 */

const journal = JSON.parse(readFileSync("drizzle/meta/_journal.json", "utf8"));

const migrations = journal.entries.map((entry) => {
  const text = readFileSync(`drizzle/${entry.tag}.sql`, "utf8");
  return {
    tag: entry.tag,
    when: entry.when,
    // Same digest drizzle-kit records when it applies a migration: the
    // sha256 of the file's bytes, unmodified.
    hash: createHash("sha256").update(text).digest("hex"),
    statements: text
      .split("--> statement-breakpoint")
      .map((s) => s.trim())
      .filter(Boolean)
      .map((s) => (s.endsWith(";") ? s : `${s};`)),
  };
});

const header = `-- The whole schema, for pasting into a SQL console.
--
-- Generated by scripts/build-schema-sql.mjs from the drizzle migrations.
-- Do not hand-edit; run \`npm run db:schema\` after changing db/schema.ts,
-- so this file and the migrations cannot quietly disagree.
--
-- Run against an empty database, in this order. To start over on one that
-- already has these tables, run docs/reset.sql first — it drops them all.
-- To see what a database currently has:
--   select name from sqlite_master where type = 'table';
--
-- Ordinary schema changes still go through drizzle:
--   npm run db:generate   (write a migration)
--   npm run db:migrate    (apply it)
-- This file is the way in when the driver cannot reach the database at
-- all, and the last two statements are what keep those two worlds
-- agreeing.
`;

const rows = migrations.map((m) => `\t('${m.hash}', ${m.when})`).join(",\n");

const footer = `
-- Drizzle's bookkeeping. The app never reads it; \`drizzle-kit migrate\`
-- does, to know what has already run. Recording the migrations this file
-- is equivalent to is what stops the next \`npm run db:migrate\` from
-- starting at 0000 and failing on tables that are already here.

CREATE TABLE \`__drizzle_migrations\` (
\t\`id\` integer PRIMARY KEY AUTOINCREMENT,
\t\`hash\` text NOT NULL,
\t\`created_at\` numeric
);

INSERT INTO \`__drizzle_migrations\` (\`hash\`, \`created_at\`) VALUES
${rows};
`;

const body = migrations.flatMap((m) => m.statements).join("\n\n");
writeFileSync("docs/schema.sql", `${header}\n${body}\n${footer}`);

console.log(
  `docs/schema.sql <- ${migrations.map((m) => m.tag).join(", ")} ` +
    `(${migrations.flatMap((m) => m.statements).length} statements)`,
);
